## Variables
# Variables are used to store data in a program. In Python, you can create a variable by simply assigning a value to a name. For example:

x = 10
y = "Hello, World!"
print("Variables:")
print(x)
print(y)

## Data Types
# Python has several built-in data types, including: 
# - int (integer)
# - float (floating-point number)
# - str (string)
# - bool (boolean)

a : int = 5
b : float = 3.14
c : str = "Python"
d : bool = True
e : bool = False

print("Data Types:")
print(type(a))
print(type(b))
print(type(c))
print(type(d))
print(type(e))

